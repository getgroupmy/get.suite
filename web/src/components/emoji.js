/** Every emoji with its group, for searching. */
export const ALL_EMOJI = EMOJI_GROUPS.flatMap(([group, list]) => list.map(([char, name, words]) => ({ char, name, words, group })));

/** Emoji whose name or search words start with each word typed ("thu up" finds thumbs up). */
export function searchEmoji(query, list = ALL_EMOJI) {
  const terms = String(query).toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return list;
  return list.filter((e) => {
    const words = `${e.name} ${e.words}`.toLowerCase().split(/[\s-]+/);
    return terms.every((t) => words.some((w) => w.startsWith(t)));
  });
}
