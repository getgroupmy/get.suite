import { chromium } from 'playwright';
const ROOT = new URL('../..', import.meta.url).pathname.replace(/\/$/, ''); // the repository
const SP = process.argv[2];
const B = process.env.BASE || 'http://localhost:8080';
const browser = await chromium.launch();
const errors = [];
let failed = 0;
const mk = async (who) => {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => errors.push(`${who}: ${e.message}`));
  p.on('console', (m) => m.type() === 'error' && !/40[0-4]|503|Content Security|sandboxed/.test(m.text()) && errors.push(`${who}: ${m.text()}`));
  return p;
};
const page = await mk('olivia');
const step = async (name, fn, p = page) => {
  try { await fn(); console.log('PASS', name); }
  catch (e) { failed++; console.log('FAIL', name, e.message.split('\n')[0], (String(e.stack).match(/e2e[\w-]*\.mjs:\d+/g) || []).slice(0, 2).join(' ')); await p.screenshot({ path: `${SP}/shots/fail-${name.replace(/\W+/g, '_')}.png` }); }
};
const api = (p, method, url, body) => p.evaluate(async ([m, u, b]) => {
  const r = await fetch('/api' + u, { method: m, headers: { 'x-requested-with': 'nas-workspace', 'content-type': 'application/json' }, body: b ? JSON.stringify(b) : undefined });
  return { status: r.status, body: await r.json().catch(() => null) };
}, [method, url, body]);
const until = async (fn, ms = 8000) => { const end = Date.now() + ms; let v; for (;;) { v = await fn(); if (v) return v; if (Date.now() > end) throw new Error('timed out'); await new Promise((r) => setTimeout(r, 150)); } };
const signIn = async (p, email) => {
  await p.goto(B);
  await p.getByLabel('Email address').fill(email);
  await p.getByLabel('Password').fill('password123');
  await p.getByRole('button', { name: 'Sign in' }).click();
  await p.getByRole('link', { name: 'Mail' }).click();
};

await step('setup', async () => {
  await page.goto(B);
  await page.getByLabel('Your company name').fill('Acme Trading');
  await page.getByLabel('Company domain').fill('acme.com');
  await page.getByLabel('Your full name').fill('Olivia Owner');
  await page.getByLabel('Address before @').fill('olivia');
  await page.getByLabel('Password', { exact: true }).fill('password123');
  await page.getByLabel('Confirm password').fill('password123');
  await page.getByRole('button', { name: 'Create workspace' }).click();
  await page.getByRole('link', { name: 'Mail' }).waitFor();
  await page.getByRole('link', { name: 'Mail' }).click();
  await page.getByText('Inbox is empty').waitFor({ timeout: 30000 });
});
await step('pick notes → Email: one new message with each under its title', async () => {
  for (const [title, body] of [['Groceries', 'Milk and eggs'], ['Trip plan', 'Beach on Sunday']]) await api(page, 'POST', '/notes', { title, body });
  await page.goto(`${B}/notes`);
  await page.getByRole('article', { name: 'Groceries' }).hover();
  await page.getByRole('button', { name: 'Select note: Groceries' }).click();
  await page.getByRole('article', { name: 'Trip plan' }).locator('.note-open').click();
  const bar = page.getByRole('toolbar', { name: 'Change the selected notes' });
  await bar.getByText('2 selected').waitFor();
  await bar.getByRole('button', { name: 'Email' }).click();
  await page.waitForURL(/\/mail/);
  const d = page.getByRole('dialog', { name: '2 notes' }).or(page.getByRole('dialog', { name: 'New message' }));
  await d.getByLabel('Subject').waitFor();
  if (await d.getByLabel('Subject').inputValue() !== '2 notes') throw new Error(await d.getByLabel('Subject').inputValue());
  const msg = d.getByRole('textbox', { name: 'Message' });
  await msg.getByText('Milk and eggs').waitFor();
  await msg.getByText('Beach on Sunday').waitFor();
  await msg.locator('strong', { hasText: 'Trip plan' }).waitFor();
});
console.log(errors.length ? `ERRORS\n${errors.join('\n')}` : 'no page errors');
await browser.close();
process.exit(failed ? 1 : 0);
